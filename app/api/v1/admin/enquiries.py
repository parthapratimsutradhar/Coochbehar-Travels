import uuid
from typing import Annotated

from fastapi import APIRouter, Depends, Path, Query, status
from sqlalchemy.orm import Session

from app.api.deps import get_current_admin_or_staff
from app.core.enums import EnquiryStatus
from app.core.messages.success import EnquirySuccess
from app.db.database import get_db
from app.models.account import Account
from app.schemas.enquiry import EnquiryCreate, EnquiryResponse, EnquiryUpdate
from app.schemas.lead import LeadResponse
from app.schemas.pagination import PaginatedResponse, PaginationMeta
from app.schemas.response import ActionResponse, ErrorResponse, SuccessResponse
from app.services.enquiry_service import EnquiryService
from app.services.lead_service import LeadService

router = APIRouter(
    prefix="/admin/enquiries",
    tags=["Admin - Enquiries"],
)


@router.post(
    "",
    response_model=ActionResponse,
    status_code=status.HTTP_201_CREATED,
    responses={401: {"model": ErrorResponse}, 403: {"model": ErrorResponse}},
    summary="Create an enquiry and its sales lead",
    description=(
        "Creates a fixed-tour or custom-tour enquiry from the submitted contact and travel details. "
        "An enquiry code and a linked sales lead are generated by the server, and the enquiry is "
        "announced to administrators. Contact fields may be supplied as `name`, `mobile` (or "
        "`phone`), and `email`. When a customer account matches the submitted mobile number or "
        "email, the enquiry is linked to that account; otherwise it remains an anonymous enquiry. "
        "Requires an authenticated admin or staff account."
    ),
)
async def create_enquiry(
    payload: EnquiryCreate,
    db: Session = Depends(get_db),
    current_user: Account = Depends(get_current_admin_or_staff),
):
    del current_user
    await EnquiryService(db).create_fixed_tour_enquiry(payload)
    return ActionResponse(message=EnquirySuccess.CREATED)


@router.get(
    "",
    response_model=PaginatedResponse[EnquiryResponse],
    responses={401: {"model": ErrorResponse}, 403: {"model": ErrorResponse}},
    summary="List and search enquiries",
    description=(
        "Returns a paginated list of enquiries, newest first. Use `status` to select an enquiry "
        "status and `customer_id` to limit results to one customer. The `search` parameter searches "
        "the enquiry code, enquirer name, phone, email, and message. Each result includes the "
        "enquiry's contact and travel details, current status, timestamps, and lead summary when "
        "available. Enquiries without a linked lead are assigned one when returned. Requires an "
        "authenticated admin or staff account."
    ),
)
def list_enquiries(
    status_filter: EnquiryStatus | None = Query(
        None,
        alias="status",
        description="Optional enquiry status filter.",
    ),
    search: str | None = Query(
        None,
        description="Search enquiry code, enquirer name, phone number, email address, or message.",
    ),
    customer_id: uuid.UUID | None = Query(
        None,
        description="Optional customer UUID; returns only enquiries linked to this customer.",
    ),
    page: int = Query(1, ge=1, description="1-based page number."),
    page_size: int = Query(20, ge=1, le=100, description="Results per page (1-100)."),
    db: Session = Depends(get_db),
    current_user: Account = Depends(get_current_admin_or_staff),
):
    service = EnquiryService(db)
    result = service.list_all_enquiries(
        page=page,
        page_size=page_size,
        status=status_filter,
        search=search,
        customer_id=customer_id,
    )
    return PaginatedResponse(
        message=EnquirySuccess.RETRIEVED,
        data=[EnquiryResponse.model_validate(e) for e in result["items"]],
        pagination=PaginationMeta(
            current_page=result["page"],
            page_size=result["page_size"],
            total_items=result["total_items"],
            total_pages=result["total_pages"],
            has_next=result["page"] < result["total_pages"],
            has_previous=result["page"] > 1,
        ),
    )


@router.get(
    "/{enquiry_id}/lead",
    response_model=SuccessResponse[LeadResponse],
    responses={401: {"model": ErrorResponse}, 403: {"model": ErrorResponse}, 404: {"model": ErrorResponse}},
    summary="Get the sales lead and activity history for an enquiry",
    description=(
        "Returns the sales lead associated with the enquiry, including its current lead details and "
        "activity history. If an older enquiry does not yet have a lead, one is created before the "
        "response is returned. Returns 404 when the enquiry or its lead cannot be found. Requires "
        "an authenticated admin or staff account."
    ),
)
def get_enquiry_lead(
    enquiry_id: Annotated[
        uuid.UUID,
        Path(description="UUID of the enquiry whose lead should be retrieved."),
    ],
    db: Session = Depends(get_db),
    current_user: Account = Depends(get_current_admin_or_staff),
):
    del current_user
    enquiry = EnquiryService(db).get_enquiry(enquiry_id)
    EnquiryService(db).ensure_lead_for_enquiry(enquiry)
    lead = LeadService(db).get_lead_for_enquiry(enquiry_id)
    return SuccessResponse(
        message=EnquirySuccess.LEAD_RETRIEVED,
        data=LeadResponse.model_validate(lead),
    )


@router.patch(
    "/{enquiry_id}",
    response_model=ActionResponse,
    responses={401: {"model": ErrorResponse}, 403: {"model": ErrorResponse}, 404: {"model": ErrorResponse}},
    summary="Update an enquiry",
    description=(
        "Partially updates an enquiry. Supply `status`, `message`, or both; omitted fields are left "
        "unchanged. Valid statuses are `NEW`, `IN_PROGRESS`, `QUOTED`, `CONVERTED`, `CANCELLED`, "
        "and `CLOSED`. A status change triggers the corresponding realtime status-update event. "
        "Returns 404 if the enquiry does not exist. Requires an authenticated admin or staff account."
    ),
)
def update_enquiry(
    enquiry_id: Annotated[
        uuid.UUID,
        Path(description="UUID of the enquiry to update."),
    ],
    payload: EnquiryUpdate,
    db: Session = Depends(get_db),
    current_user: Account = Depends(get_current_admin_or_staff),
):
    del current_user
    EnquiryService(db).update_enquiry(enquiry_id, payload)
    return ActionResponse(message=EnquirySuccess.UPDATED)
